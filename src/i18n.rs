use std::collections::HashMap;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::LazyLock;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Vi,
    En,
}

impl Lang {
    pub fn from_code(code: &str) -> Self {
        if code.eq_ignore_ascii_case("en") { Lang::En } else { Lang::Vi }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::Vi => "vi",
            Lang::En => "en",
        }
    }
}

static CURRENT: AtomicU8 = AtomicU8::new(0);

pub fn set_lang(l: Lang) {
    CURRENT.store(if l == Lang::En { 1 } else { 0 }, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    if CURRENT.load(Ordering::Relaxed) == 1 { Lang::En } else { Lang::Vi }
}

static TABLE: LazyLock<HashMap<&'static str, (&'static str, &'static str)>> =
    LazyLock::new(|| ENTRIES.iter().map(|(k, vi, en)| (*k, (*vi, *en))).collect());

pub fn t(key: &'static str) -> &'static str {
    match TABLE.get(key) {
        Some((vi, en)) => if lang() == Lang::En { en } else { vi },
        None => key,
    }
}

pub fn tf(key: &'static str, args: &[&str]) -> String {
    let mut out = t(key).to_string();
    for (i, a) in args.iter().enumerate() {
        out = out.replace(&format!("{{{}}}", i), a);
    }
    out
}

